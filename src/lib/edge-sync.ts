import { exec } from 'node:child_process';
import { chmod, mkdir, rename, writeFile } from 'node:fs/promises';
import path from 'node:path';
import { promisify } from 'node:util';
import { loadEnv } from './env';
import { normalizeCidr } from './ip';
import { log } from './logger';
import { prisma } from './prisma';

const execAsync = promisify(exec);

let running = false;
let pending = false;

/**
 * Regenerate the Nginx allowlist from the database and optionally reload Nginx.
 *
 * The application layer reads the database directly and is therefore always
 * current. This helper keeps the reverse-proxy layer in sync without a process
 * restart. It is a no-op when NGINX_ALLOWLIST_PATH is not configured. Failures
 * are logged and never break the admin operation that triggered them.
 */
export async function syncEdgeIpAllowlist(reason: string): Promise<void> {
  const env = loadEnv();
  const out = env.NGINX_ALLOWLIST_PATH?.trim();
  if (!out) return;

  if (running) {
    pending = true;
    return;
  }
  running = true;
  try {
    do {
      pending = false;
      const now = new Date();
      const rules = await prisma.ipRule.findMany({
        where: { enabled: true, OR: [{ expiresAt: null }, { expiresAt: { gt: now } }] },
        orderBy: { cidr: 'asc' },
        select: { cidr: true }
      });
      const seen = new Set<string>();
      const lines = [
        '# Generated by the application after an IP rule change — DO NOT EDIT BY HAND',
        `# ${new Date().toISOString()} — ${rules.length} active rule(s)`,
        '# Default deny: every source address not listed below is rejected by Nginx.',
        ''
      ];
      for (const rule of rules) {
        try {
          const { cidr } = normalizeCidr(rule.cidr);
          if (seen.has(cidr)) continue;
          seen.add(cidr);
          lines.push(`allow ${cidr};`);
        } catch {
          log.warn('ip.nginx_invalid_rule_skipped', { cidr: rule.cidr });
        }
      }
      lines.push('deny all;', '');
      const target = path.resolve(out);
      await mkdir(path.dirname(target), { recursive: true, mode: 0o750 });
      const tmp = `${target}.tmp-${process.pid}`;
      await writeFile(tmp, lines.join('\n'), { encoding: 'utf8', mode: 0o644 });
      await rename(tmp, target);
      await chmod(target, 0o644);
      log.info('ip.nginx_allowlist_written', { rules: seen.size, reason });

      if (env.NGINX_RELOAD_CMD) {
        try {
          await execAsync(env.NGINX_RELOAD_CMD, { timeout: 15_000 });
          log.info('ip.nginx_reloaded', { rules: seen.size });
        } catch (err) {
          log.error('ip.nginx_reload_failed', {
            error: err instanceof Error ? err.message : String(err)
          });
        }
      }
    } while (pending);
  } catch (err) {
    log.error('ip.nginx_sync_failed', {
      error: err instanceof Error ? err.message : String(err),
      reason
    });
  } finally {
    running = false;
  }
}
