import 'dotenv/config';
import { writeFile, rename, chmod } from 'node:fs/promises';
import path from 'node:path';
import { exec } from 'node:child_process';
import { promisify } from 'node:util';
import { PrismaClient } from '@prisma/client';
import { normalizeCidr } from '../src/lib/ip';

const execAsync = promisify(exec);
const prisma = new PrismaClient();

function argValue(name: string): string | undefined {
  const idx = process.argv.indexOf(name);
  return idx === -1 ? undefined : process.argv[idx + 1];
}

async function main() {
  const out = path.resolve(
    argValue('--out') ||
      process.env.NGINX_ALLOWLIST_PATH ||
      path.join(process.cwd(), 'deploy/nginx/ip-allow.generated.conf')
  );
  const reload = process.argv.includes('--reload');
  const now = new Date();
  const rules = await prisma.ipRule.findMany({
    where: { enabled: true, OR: [{ expiresAt: null }, { expiresAt: { gt: now } }] },
    orderBy: { cidr: 'asc' }
  });

  const lines = [
    '# Generated by scripts/sync-nginx-allowlist.ts — DO NOT EDIT BY HAND',
    `# ${new Date().toISOString()} — ${rules.length} active rule(s)`,
    '# Default deny: every source address not listed below is rejected by Nginx.',
    ''
  ];
  const seen = new Set<string>();
  for (const rule of rules) {
    try {
      const { cidr } = normalizeCidr(rule.cidr);
      if (seen.has(cidr)) continue;
      seen.add(cidr);
      lines.push(`allow ${cidr};`);
    } catch {
      console.error(`skip invalid CIDR from database: ${rule.id}`);
    }
  }
  lines.push('deny all;', '');

  const tmp = `${out}.tmp`;
  await writeFile(tmp, lines.join('\n'), { encoding: 'utf8', mode: 0o644 });
  await rename(tmp, out);
  await chmod(out, 0o644);
  console.log(`Wrote ${seen.size} allow rules to ${out} (deny all fallback)`);

  if (reload) {
    const cmd = process.env.NGINX_RELOAD_CMD;
    if (!cmd) {
      console.error('NGINX_RELOAD_CMD is not configured; file written but Nginx was not reloaded.');
      process.exitCode = 1;
      return;
    }
    try {
      const { stdout, stderr } = await execAsync(cmd, { timeout: 15_000 });
      if (stdout.trim()) console.log(stdout.trim());
      if (stderr.trim()) console.error(stderr.trim());
      console.log('Nginx reload command completed.');
    } catch (err) {
      console.error(`Nginx reload failed: ${err instanceof Error ? err.message : String(err)}`);
      process.exitCode = 1;
    }
  }
}

main()
  .catch((err) => {
    console.error(err instanceof Error ? err.message : String(err));
    process.exitCode = 1;
  })
  .finally(async () => {
    await prisma.$disconnect();
  });
